import React, { useState } from 'react';
import { 
  X, 
  FileText, 
  Copy, 
  Check, 
  Download, 
  ShieldCheck, 
  Lock, 
  Globe, 
  CheckCircle2, 
  ExternalLink,
  Code2,
  Building,
  Info
} from 'lucide-react';

export interface SecurityTxtLegalGeneratorModalProps {
  isOpen: boolean;
  onClose: () => void;
  storeUrl?: string;
  email?: string;
}

export const SecurityTxtLegalGeneratorModal: React.FC<SecurityTxtLegalGeneratorModalProps> = ({
  isOpen,
  onClose,
  storeUrl = 'https://ma-boutique-en-ligne.fr',
  email = 'contact@ma-boutique-en-ligne.fr'
}) => {
  const [activeTab, setActiveTab] = useState<'security_txt' | 'legal_pack' | 'guide'>('security_txt');
  const [securityEmail, setSecurityEmail] = useState<string>(email);
  const [disclosureUrl, setDisclosureUrl] = useState<string>(`${storeUrl}/divulgation-responsable`);
  const [copiedTxt, setCopiedTxt] = useState<boolean>(false);
  const [copiedLegal, setCopiedLegal] = useState<boolean>(false);

  if (!isOpen) return null;

  const sanitizeDirective = (val: string) => (val || '').replace(/[\r\n\t]/g, '').trim();
  const cleanDomain = sanitizeDirective(storeUrl.replace(/^https?:\/\//i, '').split('/')[0]) || 'ma-boutique-en-ligne.fr';
  const safeSecurityEmail = sanitizeDirective(securityEmail);
  const safeDisclosureUrl = sanitizeDirective(disclosureUrl);
  const nextYear = new Date();
  nextYear.setFullYear(nextYear.getFullYear() + 1);
  const expiresIso = nextYear.toISOString();

  // Contenu conforme RFC 9116 standard IETF
  const securityTxtContent = `# Official security.txt file for ${cleanDomain}
# Compliant with IETF RFC 9116
# See https://securitytxt.org/

Contact: mailto:${safeSecurityEmail}
Policy: ${safeDisclosureUrl}
Preferred-Languages: fr, en
Canonical: https://${cleanDomain}/.well-known/security.txt
Expires: ${expiresIso}
Acknowledgments: https://${cleanDomain}/securite/remerciements

# Generated by BoutiqueSûre - Cybersecurity for E-Commerce
`;

  // Pack mentions légales e-commerce (DGCCRF & CNIL)
  const legalPackContent = `## Mentions Légales & Politique de Sécurité des Données
**Site :** ${cleanDomain}
**Date de révision :** ${new Date().toLocaleDateString('fr-FR')}

### 1. Protection des Transactions Bancaires (PCI-DSS)
Les règlements par carte bancaire sont traités via des passerelles certifiées PCI-DSS Niveau 1 (ex: Stripe, Payplug, Mollie). 
Aucune donnée bancaire (numéro complet, CVV) ne transite ni n'est stockée sur nos serveurs.

### 2. Sous-Traitants & Chiffrement des Flux
Tous les flux d'échange entre votre terminal et notre boutique en ligne sont protégés par un chiffrement SSL/TLS fort (AES-256) avec forçage HTTPS et directive HSTS.
- **Hébergement sécurisé :** Union Européenne (RGPD compliant).
- **Transporteurs partenaires :** Transmission exclusive des données strictes de livraison.

### 3. Signalement Éthique de Vulnérabilités (RFC 9116)
Conformément aux bonnes pratiques de cybersécurité, notre boutique dispose d'un canal officiel de signalement éthique accessible à l'adresse :
https://${cleanDomain}/.well-known/security.txt
Pour tout signalement : ${securityEmail}
`;

  const handleCopySecurityTxt = async () => {
    try {
      await navigator.clipboard.writeText(securityTxtContent);
    } catch {
      const textarea = document.createElement('textarea');
      textarea.value = securityTxtContent;
      document.body.appendChild(textarea);
      textarea.select();
      document.execCommand('copy');
      document.body.removeChild(textarea);
    }
    setCopiedTxt(true);
    setTimeout(() => setCopiedTxt(false), 2500);
  };

  const handleCopyLegalPack = async () => {
    try {
      await navigator.clipboard.writeText(legalPackContent);
    } catch {
      const textarea = document.createElement('textarea');
      textarea.value = legalPackContent;
      document.body.appendChild(textarea);
      textarea.select();
      document.execCommand('copy');
      document.body.removeChild(textarea);
    }
    setCopiedLegal(true);
    setTimeout(() => setCopiedLegal(false), 2500);
  };

  const handleDownloadFile = () => {
    const element = document.createElement('a');
    const file = new Blob([securityTxtContent], { type: 'text/plain;charset=utf-8' });
    element.href = URL.createObjectURL(file);
    element.download = 'security.txt';
    document.body.appendChild(element);
    element.click();
    document.body.removeChild(element);
  };

  return (
    <div 
      className="fixed inset-0 z-50 bg-slate-950/80 backdrop-blur-sm flex items-center justify-center p-4 overflow-y-auto"
      data-testid="security-txt-legal-modal"
    >
      <div className="bg-slate-900 border border-slate-800 rounded-3xl max-w-3xl w-full p-6 sm:p-8 shadow-2xl space-y-6 max-h-[90vh] flex flex-col justify-between my-auto">
        
        {/* Header */}
        <div className="flex items-center justify-between pb-4 border-b border-slate-800">
          <div className="flex items-center gap-3">
            <div className="w-10 h-10 rounded-2xl bg-emerald-500/10 border border-emerald-500/20 flex items-center justify-center text-emerald-400">
              <FileText className="w-5 h-5" />
            </div>
            <div>
              <h2 className="text-lg sm:text-xl font-black text-white">
                Générateur Officiel security.txt (RFC 9116)
              </h2>
              <p className="text-xs text-slate-300">
                Standard international IETF pour protéger votre boutique et recevoir les signalements éthiques
              </p>
            </div>
          </div>
          <button
            type="button"
            onClick={onClose}
            data-testid="close-security-txt-modal-btn"
            className="p-2 rounded-xl bg-slate-800/80 hover:bg-slate-800 text-slate-400 hover:text-white transition-colors cursor-pointer"
          >
            <X className="w-5 h-5" />
          </button>
        </div>

        {/* Navigation Onglets */}
        <div className="flex items-center gap-2 border-b border-slate-800 pb-2">
          <button
            type="button"
            onClick={() => setActiveTab('security_txt')}
            className={`px-3.5 py-1.5 rounded-xl text-xs font-bold transition-all cursor-pointer ${
              activeTab === 'security_txt'
                ? 'bg-emerald-400 text-slate-950 shadow-md'
                : 'text-slate-400 hover:text-white bg-slate-800/50'
            }`}
          >
            1. Fichier security.txt (RFC 9116)
          </button>
          <button
            type="button"
            onClick={() => setActiveTab('legal_pack')}
            className={`px-3.5 py-1.5 rounded-xl text-xs font-bold transition-all cursor-pointer ${
              activeTab === 'legal_pack'
                ? 'bg-emerald-400 text-slate-950 shadow-md'
                : 'text-slate-400 hover:text-white bg-slate-800/50'
            }`}
          >
            2. Pack Mentions Légales E-Commerce
          </button>
          <button
            type="button"
            onClick={() => setActiveTab('guide')}
            className={`px-3.5 py-1.5 rounded-xl text-xs font-bold transition-all cursor-pointer ${
              activeTab === 'guide'
                ? 'bg-emerald-400 text-slate-950 shadow-md'
                : 'text-slate-400 hover:text-white bg-slate-800/50'
            }`}
          >
            3. Guide de Déploiement
          </button>
        </div>

        {/* Corps Onglet 1: security.txt */}
        {activeTab === 'security_txt' && (
          <div className="space-y-4 overflow-y-auto pr-1">
            <div className="grid grid-cols-1 sm:grid-cols-2 gap-3 text-xs">
              <div>
                <label className="font-bold text-slate-300 block mb-1">Email de signalement sécurité :</label>
                <input
                  type="email"
                  value={securityEmail}
                  onChange={(e) => setSecurityEmail(e.target.value)}
                  className="w-full px-3 py-2 rounded-xl bg-slate-950 border border-slate-800 text-white font-mono text-xs focus:outline-none focus:ring-2 focus:ring-emerald-400"
                />
              </div>
              <div>
                <label className="font-bold text-slate-300 block mb-1">Page de politique (divulgation) :</label>
                <input
                  type="text"
                  value={disclosureUrl}
                  onChange={(e) => setDisclosureUrl(e.target.value)}
                  className="w-full px-3 py-2 rounded-xl bg-slate-950 border border-slate-800 text-white font-mono text-xs focus:outline-none focus:ring-2 focus:ring-emerald-400"
                />
              </div>
            </div>

            <div className="relative">
              <pre className="p-4 rounded-2xl bg-slate-950 border border-slate-800 text-xs font-mono text-emerald-300 overflow-x-auto whitespace-pre-wrap leading-relaxed max-h-56">
                {securityTxtContent}
              </pre>
            </div>

            <div className="flex flex-col sm:flex-row items-center justify-between gap-3 pt-2">
              <span className="text-[11px] text-slate-400">
                Emplacement standard : <code className="text-emerald-400 font-mono">/.well-known/security.txt</code>
              </span>
              <div className="flex items-center gap-2 w-full sm:w-auto">
                <button
                  type="button"
                  onClick={handleCopySecurityTxt}
                  data-testid="copy-security-txt-btn"
                  className="flex-1 sm:flex-initial px-4 py-2 rounded-xl bg-slate-800 hover:bg-slate-700 text-white text-xs font-bold transition-all flex items-center justify-center gap-2 cursor-pointer"
                >
                  {copiedTxt ? <Check className="w-3.5 h-3.5 text-emerald-400" /> : <Copy className="w-3.5 h-3.5" />}
                  <span>{copiedTxt ? 'Copié !' : 'Copier'}</span>
                </button>
                <button
                  type="button"
                  onClick={handleDownloadFile}
                  data-testid="download-security-txt-btn"
                  className="flex-1 sm:flex-initial px-4 py-2 rounded-xl bg-emerald-400 hover:bg-emerald-300 text-slate-950 text-xs font-black transition-all flex items-center justify-center gap-2 cursor-pointer shadow-md"
                >
                  <Download className="w-3.5 h-3.5" />
                  <span>Télécharger .txt</span>
                </button>
              </div>
            </div>
          </div>
        )}

        {/* Corps Onglet 2: Mentions Légales E-Commerce */}
        {activeTab === 'legal_pack' && (
          <div className="space-y-4 overflow-y-auto pr-1">
            <p className="text-xs text-slate-300">
              Insérez ces paragraphes dans vos mentions légales et CGV pour attester de votre conformité PCI-DSS et RGPD :
            </p>
            <pre className="p-4 rounded-2xl bg-slate-950 border border-slate-800 text-xs font-mono text-slate-300 overflow-x-auto whitespace-pre-wrap leading-relaxed max-h-56">
              {legalPackContent}
            </pre>
            <div className="flex justify-end pt-2">
              <button
                type="button"
                onClick={handleCopyLegalPack}
                data-testid="copy-legal-pack-btn"
                className="px-4 py-2 rounded-xl bg-emerald-400 hover:bg-emerald-300 text-slate-950 text-xs font-black transition-all flex items-center gap-2 cursor-pointer shadow-md"
              >
                {copiedLegal ? <Check className="w-3.5 h-3.5" /> : <Copy className="w-3.5 h-3.5" />}
                <span>{copiedLegal ? 'Copié !' : 'Copier le texte légal'}</span>
              </button>
            </div>
          </div>
        )}

        {/* Corps Onglet 3: Guide de déploiement */}
        {activeTab === 'guide' && (
          <div className="space-y-3 overflow-y-auto pr-1 text-xs text-slate-300 leading-relaxed">
            <div className="p-3.5 rounded-xl bg-slate-950 border border-slate-800 space-y-1">
              <strong className="text-white block">🛒 Sur Shopify :</strong>
              <p className="text-slate-400">
                Téléchargez le fichier <code className="text-emerald-400 font-mono">security.txt</code> dans Paramètres &gt; Fichiers, ou créez une redirection d'URL de <code className="text-emerald-400 font-mono">/.well-known/security.txt</code> vers votre page de politique de sécurité.
              </p>
            </div>
            <div className="p-3.5 rounded-xl bg-slate-950 border border-slate-800 space-y-1">
              <strong className="text-white block">🛍️ Sur WooCommerce / WordPress :</strong>
              <p className="text-slate-400">
                Créez le dossier <code className="text-emerald-400 font-mono">.well-known</code> à la racine de votre hébergement FTP/SSH et déposez-y le fichier <code className="text-emerald-400 font-mono">security.txt</code>.
              </p>
            </div>
            <div className="p-3.5 rounded-xl bg-slate-950 border border-slate-800 space-y-1">
              <strong className="text-white block">📦 Sur PrestaShop / Magento / Serveur Nginx/Apache :</strong>
              <p className="text-slate-400">
                Déposez directement le fichier dans <code className="text-emerald-400 font-mono">/var/www/html/.well-known/security.txt</code>.
              </p>
            </div>
          </div>
        )}

        {/* Footer */}
        <div className="pt-4 border-t border-slate-800 flex items-center justify-between text-xs text-slate-400">
          <span className="flex items-center gap-1.5 text-emerald-400">
            <CheckCircle2 className="w-3.5 h-3.5" />
            Standard RFC 9116 officiel
          </span>
          <button
            type="button"
            onClick={onClose}
            className="px-4 py-2 rounded-xl bg-slate-800 hover:bg-slate-700 text-white font-bold transition-colors cursor-pointer"
          >
            Fermer
          </button>
        </div>

      </div>
    </div>
  );
};

export default SecurityTxtLegalGeneratorModal;
